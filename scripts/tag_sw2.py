def build_index():
    idx, dup = {}, []
    for code2, (name, codes) in SW2.items():
        for c in codes:
            if c in idx:
                dup.append((c, idx[c], code2))
            idx[c] = (code2, name)
    return idx, dup


def main() -> int:
    check_only = "--check" in sys.argv
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    cs = payload["companies"]

    idx, dup = build_index()
    if dup:
        print("[ERROR] 代码被重复分配到两个二级类目：")
        for c, a, b in dup:
            print(f"  {c}: {a} vs {b}")
        return 1

    missing = [(c["code"], c["name"], c["industry"]) for c in cs if c["code"] not in idx]
    ghost = [k for k in idx if k not in {c["code"] for c in cs}]
    if missing:
        print(f"[WARN] {len(missing)} 家未分配二级类目：")
        for m in missing:
            print(f"  {m[0]} {m[1]} ({m[2]})")
    if ghost:
        print(f"[WARN] 映射里有主数据不存在的代码：{ghost}")

    # 一级与二级的归属一致性：同一 SW2 编码下的公司应属同一 industry
    from collections import defaultdict
    ind_of = defaultdict(set)
    for c in cs:
        if c["code"] in idx:
            ind_of[idx[c["code"]][0]].add(c["industry"])
    cross = {k: v for k, v in ind_of.items() if len(v) > 1}
    if cross:
        print("[ERROR] 同一二级类目横跨多个一级行业：")
        for k, v in cross.items():
            print(f"  {k} {SW2[k][0]}: {sorted(v)}")
        return 1

    for c in cs:
        if c["code"] in idx:
            c["sw1"] = c["industry"]
            c["sw2_code"], c["sw2"] = idx[c["code"]]

    # 类目规模分布
    from collections import Counter
    sizes = Counter(name for _, name in idx.values())
    bucket = Counter(sizes.values())
    print(f"[INFO] {len(idx)} 家公司映射到 {len(SW2)} 个二级类目")
    print("[INFO] 类目规模分布：" + "  ".join(f"{n}家×{k}个" for n, k in sorted(bucket.items())))
    solo = sorted(n for n, k in sizes.items() if k == 1)
    print(f"[INFO] 单一公司类目 {len(solo)} 个（不做横向对比，仅作标签）：")
    print("       " + "、".join(solo))

    if check_only:
        print("[CHECK] 未写文件")
        return 0
    DATA.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"[OK] 写入 {DATA}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
