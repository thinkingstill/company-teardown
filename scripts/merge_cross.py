def main():
    data = json.loads(DATA.read_text(encoding="utf-8"))
    existing = {c["code"]: c for c in data["companies"]}
    added = 0
    for c in CROSS:
        old = existing.get(c["code"])
        if old:
            # 保护已补充的长序列与估值：本文件的 CROSS 只写 2021–2025 基线，
            # 若库里的序列更长（已由 merge_cross_long.py 补到上市年），
            # 保留更长的 years 与 coverage，避免重跑本脚本时把长序列打回去。
            old_years = {d["y"] for d in old.get("years", [])}
            new_years = {d["y"] for d in c["years"]}
            if old_years and (min(old_years) < min(new_years) or len(old_years) > len(new_years)):
                merged = list(c["years"]) + [d for d in old["years"] if d["y"] not in new_years]
                merged.sort(key=lambda d: d["y"])
                c = dict(c, years=merged, coverage=[merged[0]["y"], merged[-1]["y"]])
                if old.get("years_pre"):
                    c["years_pre"] = old["years_pre"]
                print(f"[KEEP] {c['code']} 保留 {len(merged)} 个财年的长序列")
            # 估值与叙事补充字段不归本脚本管，原样带过来
            for k in ("valuation", "financial"):
                if old.get(k):
                    c[k] = old[k]
            existing[c["code"]] = c
        else:
            data["companies"].append(c)
            existing[c["code"]] = c
            added += 1
    data["companies"].sort(key=lambda x: (x["coverage"][0], x["code"]))
    data["meta"]["batch"] = f"v3 · {len(data['companies'])} 家 · 2026-11"
    data["meta"]["as_of"] = "2025 财年（阿里为 FY2025）"
    DATA.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    total_years = sum(len(c["years"]) for c in data["companies"])
    print(f"跨市场合并：新增 {added} 家，合计 {len(data['companies'])} 家 / {total_years} 财年")


if __name__ == "__main__":
    main()
